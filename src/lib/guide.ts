/**
 * **앱 사용자 가이드의 글** — 웹 `screens/Help.tsx`와 앱 `HelpViewController.swift`가
 * **같은 글을 쓴다.** 두 벌로 두면 화면 문구를 고칠 때 한쪽만 고치게 되므로
 * 글은 여기 한 곳에만 있고, 앱은 화면을 열 때 이 표를 통째로 실어 받는다
 * (`NativeScreenHost`의 `guide` — 대화 화면이 이모티콘 추천 표를 받는 것과
 * 같은 방식이다).
 *
 * **표시는 두 가지뿐이다** — `**굵게**`와 `((곁말))`(옅은 글자 · 안 읽어도 되는
 * 줄). 웹의 `Rich`와 Swift의 `GuideText`가 같은 규칙으로 푼다.
 *
 * **말투는 사용자가 정한 것이다**(전문적인 안내문). 구어체로 되돌리지 말 것.
 * **여기 적힌 버튼 이름은 실제 화면의 말이다** — 화면 문구를 바꾸면 여기도
 * 함께 고쳐야 설명이 거짓말이 안 된다.
 *
 * 9번의 `홈 화면에 추가`는 **웹으로 쓰는 동안만 필요한 안내다.** 앱으로
 * 쓰면 그 단계가 없으므로 `webOnly`로 표시해 앱 화면에서는 뺀다.
 */
export type GuideStep = { text: string; webOnly?: boolean };
export type GuidePart = {
    n: number;
    icon: string;
    title: string;
    lead?: string;
    /** 점 목록 — 설명이 나열되는 자리. */
    items?: string[];
    /** 번호가 붙는 단계 — 손으로 따라 할 일에만 쓴다. */
    steps?: GuideStep[];
    /** 곁들이는 말 — 옅은 바탕. */
    tip?: string;
};

