/**
 * 축하하는 말이 오가면 **폭죽 단추**가 뜬다 — 카톡의 그것이다
 * (사용자 요청 — `채팅창에 ㅊㅋ,축하,ㅊㅋㅊㅋ,추카 문구를 입력하고
 * 전송을하면 메시지입력창 윗쪽에 카톡처럼 폭죽버튼이 나오고 그걸 누르면
 * 카톡처럼 화면에 폭죽이 나오는 기능`).
 *
 * **보낸 사람만이 아니라 방에 있는 모두에게 뜬다.** 카톡이 그렇고, 축하는
 * 원래 여럿이 함께 하는 것이라 보낸 사람 혼자 폭죽을 보는 것은 뜻이 없다.
 * **누르는 사람의 화면에서만 터진다** — 남의 화면을 우리가 건드리지 않는다.
 *
 * **글에 아무것도 저장하지 않는다.** `@언급`·링크와 같은 결이다 —
 * 그릴 때 글자를 보고 가리므로, 말을 늘리면 **예전 글에도 그대로 먹는다**
 * (DB에 칸을 더할 일도, 붙여넣을 SQL도 없다).
 */

/**
 * 이 말이 들어 있으면 축하다.
 *
 * **사용자가 적어 준 넷 그대로다** — `ㅊㅋ` · `축하` · `ㅊㅋㅊㅋ` · `추카`.
 * `ㅊㅋㅊㅋ`는 `ㅊㅋ`에 이미 걸리므로 따로 안 적는다. 같은 까닭으로
 * `축하해`·`축하합니다`·`추카추카`도 저절로 걸린다.
 *
 * **함부로 늘리지 말 것.** `ㅊ`이나 `ㅋㅋ`까지 넣으면 웃는 말마다 폭죽
 * 단추가 떠서, 정작 축하할 때 아무도 안 누른다.
 */
const WORDS = ['축하', '추카', 'ㅊㅋ'];

/**
 * 이 글이 축하하는 말인가.
 *
 * **사진·이모티콘에 딸린 글도 본다** — 사진을 올리면서 `축하!`라고 적는
 * 것이 오히려 흔하다. **안내 줄(`system`)도 그대로 본다**: 생일 축하 글이
 * 그 갈래라 그 줄에서도 단추가 떠야 한다(`post_birthday_greetings`가
 * 문구에 `축하`를 넣어 두는 까닭이다).
 */
export function isCheer(body?: string | null): boolean {
    const t = (body ?? '').replace(/\s/g, '');
    if (!t) return false;
    return WORDS.some(w => t.includes(w));
}

/**
 * 단추가 떠 있는 시간(ms).
 *
 * **영영 두지 않는다.** 축하는 그 자리에서 하는 것이라, 한참 뒤에 들어와
 * 어제 것으로 폭죽을 터뜨리면 무엇을 축하하는지 알 수가 없다. 카톡도
 * 잠깐 떠 있다 사라진다.
 */
export const CHEER_MS = 60_000;
