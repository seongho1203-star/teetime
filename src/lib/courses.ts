/** 띄어쓰기와 대소문자를 지운 이름. `사우스링스 영암`과 `사우스링스영암`은 같은 곳이다. */
const key = (s: string) => s.replace(/\s+/g, '').toLowerCase();

const byKey = new Map(COURSES.map(c => [key(c.name), c]));

/**
 * 이름으로 좌표를 찾는다.
 *
 * 딱 맞는 것이 없으면 **이름이 들어 있는 곳 중 가장 긴 것**을 쓴다 —
 * `화순`과 `화순CC`가 같이 걸릴 때 뒤엣것이 맞다. 못 찾으면 null이고,
 * 그때는 날씨칸만 빠진다.
 */
export function courseGeo(name: string | null | undefined): Course | null {
    if (!name) return null;
    const k = key(name);
    if (!k) return null;

    const exact = byKey.get(k);
    if (exact) return exact;

    let best: Course | null = null;
    for (const c of COURSES) {
        const ck = key(c.name);
        if (!k.includes(ck) && !ck.includes(k)) continue;
        if (!best || ck.length > key(best.name).length) best = c;
    }
    return best;
}

/** 검색창에 칠 때 보여 줄 몇 곳. 이름 어디에든 들어 있으면 걸린다. */
export function searchCourses(q: string, limit = 8): Course[] {
    const k = key(q);
    if (!k) return [];
    const hit = COURSES.filter(c => key(c.name).includes(k));
    // 이름이 짧을수록(= 군더더기가 적을수록) 먼저 보여 준다.
    hit.sort((a, b) => a.name.length - b.name.length);
    return hit.slice(0, limit);
}
