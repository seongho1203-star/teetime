/** 골프장 이름을 표 열쇠 모양으로 — 띄어쓰기와 끝의 `CC`·`컨트리클럽` 따위를 뗀다.
 *  **딱 맞을 때만 쓴다** — `화순`과 `화순엘리체`는 다른 골프장이다. */
export function clubKey(name: string): string {
    return String(name || '').replace(/\s+/g, '')
        .replace(/(CC|GC|컨트리클럽|골프클럽|골프장|골프앤리조트|골프리조트|골프링크스|골프클럽스)$/i, '');
}
